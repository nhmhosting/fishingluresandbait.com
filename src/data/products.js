// Function to derive makes and models for a product
// This analyzes the product's brand, categories, and name to determine which makes/models it fits
// Also includes API-provided make_ids and model_ids from database relationships
export function getProductMakes(product) {
    const productMakes = new Set();
    const productModels = new Set();
    const cats = product.categories || [product.category];
    const nameDesc = (product.name + ' ' + product.description).toLowerCase();

    // Include API-provided make_ids (from database relationships - "Additional Brands")
    // Note: thomas-minotour is stored as a "brand" in admin but is actually a model under thomas
    if (product.make_ids && Array.isArray(product.make_ids)) {
        product.make_ids.forEach(makeId => {
            if (makeId === 'thomas-minotour') {
                // thomas-minotour is a model, not a make - map to thomas make
                productMakes.add('thomas');
                productModels.add('thomas-minotour');
            } else {
                productMakes.add(makeId);
            }
        });
    }

    // Include API-provided model_ids (from database relationships)
    if (product.model_ids && Array.isArray(product.model_ids)) {
        product.model_ids.forEach(modelId => productModels.add(modelId));
    }

    // Analyze by brand
    if (product.brand === 'bluebird') {
        productMakes.add('bluebird');
        // Check for specific models in name/description
        if (nameDesc.includes('vision')) productModels.add('bluebird-vision');
        if (nameDesc.includes('all american')) productModels.add('bluebird-all-american');
        if (nameDesc.includes('conventional')) productModels.add('bluebird-conventional');
    }

    if (product.brand === 'thomas') {
        productMakes.add('thomas');
    }

    if (product.brand === 'thomas-minotour') {
        productMakes.add('thomas');
        productModels.add('thomas-minotour');
    }

    if (product.brand === 'international') {
        productMakes.add('international');
        // Check for Genesis model
        if (nameDesc.includes('genesis')) {
            productModels.add('international-genesis');
        } else {
            productModels.add('international-ic');
        }
    }

    if (product.brand === 'collins') {
        productMakes.add('collins');
    }

    if (product.brand === 'universal') {
        productMakes.add('universal');
    }

    // Analyze by categories to determine models
    cats.forEach(cat => {
        // Thomas C2 categories
        if (cat.startsWith('thomas-c2')) {
            productMakes.add('thomas');
            productModels.add('thomas-c2');
        }
        // Thomas FS65 categories
        if (cat.startsWith('thomas-fs65')) {
            productMakes.add('thomas');
            productModels.add('thomas-fs65');
        }
        // Thomas Minotour categories
        if (cat.startsWith('thomas-minotour')) {
            productMakes.add('thomas');
            productModels.add('thomas-minotour');
        }
        // Thomas general categories (could fit multiple models)
        if (cat.startsWith('thomas-') && !cat.startsWith('thomas-c2') && !cat.startsWith('thomas-fs65') && !cat.startsWith('thomas-minotour')) {
            productMakes.add('thomas');
            // General Thomas parts could fit any Thomas model
        }
        // Blue Bird categories
        if (cat.startsWith('blue-bird')) {
            productMakes.add('bluebird');
        }
        // International categories
        if (cat.startsWith('international')) {
            productMakes.add('international');
            if (!nameDesc.includes('genesis')) {
                productModels.add('international-ic');
            }
        }
        // Collins categories
        if (cat.startsWith('collins')) {
            productMakes.add('collins');
        }
    });

    // Also check name patterns for model identification
    if (nameDesc.includes('c2') || nameDesc.includes('saf-t-liner')) {
        productMakes.add('thomas');
        productModels.add('thomas-c2');
    }
    if (nameDesc.includes('fs65') || nameDesc.includes('fs-65')) {
        productMakes.add('thomas');
        productModels.add('thomas-fs65');
    }
    if (nameDesc.includes('minotour') || nameDesc.includes('minotaur')) {
        productMakes.add('thomas');
        productModels.add('thomas-minotour');
    }

    return {
        makes: [...productMakes],
        models: [...productModels]
    };
}

// Get all products with their makes/models computed
export function getProductsWithMakes() {
    return products.map(product => ({
        ...product,
        ...getProductMakes(product)
    }));
}

// Filter products by make
export function filterProductsByMake(makeId) {
    return products.filter(product => {
        const { makes } = getProductMakes(product);
        return makes.includes(makeId);
    });
}

// Filter products by model
export function filterProductsByModel(modelId) {
    return products.filter(product => {
        const { models } = getProductMakes(product);
        return models.includes(modelId);
    });
}

// Search function
export function searchProducts(query) {
    const normalizedQuery = query.toLowerCase().trim();
    if (!normalizedQuery) return products;

    return products.filter(product => {
        const searchFields = [
            product.id,
            product.name,
            product.description,
            product.brand,
            product.category,
            ...(product.categories || [])
        ].filter(Boolean).map(f => f.toLowerCase());

        return searchFields.some(field => field.includes(normalizedQuery));
    });
}

// Get product by ID
export function getProductById(id) {
    return products.find(product => product.id === id);
}

// Get product by slug (same as ID for this site)
export function getProductBySlug(slug) {
    return products.find(product => product.id === slug);
}

// Get featured products for homepage
// mode: 'all' returns first N products (default), brand name filters by brand
export function getFeaturedProducts(count = 8, mode = 'all') {
    if (mode === 'all') {
        return products.slice(0, count);
    }
    return products.filter(p => p.brand === mode).slice(0, count);
}
